//! `head_facts` —— **输入头里那几格**（切片器自己写在 `;` 注释里的）：喷嘴直径 / 层高 /
//! 切片软件版本。跑管线**之前**就能给（读文件那一刻就有），所以界面开场那张表不必摆 `—`。
//!
//! # 为什么单独一个模块（2026-10-14）
//!
//! 作者在真机上看那张表：「它怎么就不显示那一个喷嘴层高那一些，获取不到吗？怎么可能呢，
//! 肯定获取得到」。对 —— 那两行就在文件前几百行里（`; nozzle_diameter = 0.4`、
//! `; layer_height = 0.2`）。原来它们只在 [`crate::postproc::pass1`] 的逐行循环里认，
//! 而那条路**开场还没跑到**：钩子把「机型与切片基础」推给界面时，pass1 连第一行都没读。
//! 于是界面只好摆 `—`，跑完也不补（事实那几格只在开场报一次）。
//!
//! 切片软件版本同一回事：`; BambuStudio 02.08.02.60` 也在头里（第一遍扫描才刮到它，
//! 所以"跑着"那阵只能摆预设里的名字，跑完才换成完整串）。作者问「处理过程中他是不知道
//! BBS 的那个版本的吗」—— 知道，头里写着。
//!
//! # 口径
//!
//! 认这几行**只认切片器自己写的那一种形态**（与 pass1 逐字同源，别在这里发明第二种写法）：
//!
//! - `; nozzle_diameter = <f64>`（[`crate::postproc::pass1`] 那条同款，含尾空格）
//! - `; layer_height = <f64>`（同上；`; initial_layer_print_height` 不算 —— 那是首层高）
//! - `; BambuStudio | OrcaSlicer | PrusaSlicer <ver>`（pass1 认 `stats.slicer_version` 的同一串）
//!
//! 缺哪行 ⇒ 那一格 `None`（界面照旧摆 `—`），**不编也不兜底** —— 兜底（0.4 / 0.2）是
//! [`crate::ir::defaults`] 的活，只喂内核自己算，不冒充"这份文件自报的"。

/// 输入头里那几格。三格都可以缺（老 G-code / 别的切片器 / 输入被裁过）。
#[derive(Debug, Clone, Default, PartialEq)]
pub struct HeadFacts {
    pub nozzle_diameter: Option<f64>,
    pub layer_height: Option<f64>,
    /// 完整串（`"BambuStudio 02.08.02.60"`）—— 与跑完后 `result.slicer` 同源同形。
    pub slicer_version: Option<String>,
}

/// 认输入头那几行。逐行扫到 `; config_block_end` 为止（后面的正文不再当头部看，
/// 与 [`crate::postproc::printtime`] 的 `parse_header_meta` 同一条边界）；三格都认到就提前收工。
pub fn read_head_facts(content: &str) -> HeadFacts {
    let mut out = HeadFacts::default();
    for raw in content.lines() {
        let s = raw.trim();
        if s.starts_with("; config_block_end") {
            break;
        }
        if !s.starts_with(';') {
            continue;
        }
        /* 每格只认第一次出现的（切片器把生效值写在头里；重复出现属于异常，不跟着后面跑） */
        if out.nozzle_diameter.is_none()
            && s.contains("; nozzle_diameter = ")
            && let Some(n) = first_number(s)
        {
            out.nozzle_diameter = Some(n);
        }
        if out.layer_height.is_none()
            && s.contains("; layer_height = ")
            && let Some(n) = first_number(s)
        {
            out.layer_height = Some(n);
        }
        if out.slicer_version.is_none()
            && (s.contains("; BambuStudio ")
                || s.contains("; OrcaSlicer ")
                || s.contains("; PrusaSlicer "))
        {
            out.slicer_version = Some(s.strip_prefix("; ").unwrap_or(s).to_string());
        }
        if out.nozzle_diameter.is_some()
            && out.layer_height.is_some()
            && out.slicer_version.is_some()
        {
            break;
        }
    }
    out
}

/// 这一行里第一个数（与 `ir::num_strip` 同一判据的轻量版：找连续 `[0-9.]` 段再解析）。
/// 不用 `ir::num_strip` 是为了不把 `crate::ir` 牵进来 —— 这一格只吃头部注释，不需要 IR。
fn first_number(line: &str) -> Option<f64> {
    let bytes = line.as_bytes();
    let mut i = 0;
    while i < bytes.len() {
        let c = bytes[i];
        if c.is_ascii_digit() {
            let start = i;
            while i < bytes.len() && (bytes[i].is_ascii_digit() || bytes[i] == b'.') {
                i += 1;
            }
            if let Ok(v) = line[start..i].parse::<f64>() {
                return Some(v);
            }
        } else {
            i += 1;
        }
    }
    None
}

#[cfg(test)]
mod tests {
    use super::*;

    const HEAD: &str = "\
; BambuStudio 02.08.02.60
; model printing time: 3h 22m 55s; total estimated time: 3h 22m 55s
; initial_layer_print_height = 0.2
; layer_height = 0.2
; nozzle_diameter = 0.4
; config_block_end
; nozzle_diameter = 9.9
";

    #[test]
    fn reads_the_three_cells() {
        let f = read_head_facts(HEAD);
        assert_eq!(f.nozzle_diameter, Some(0.4));
        /* `; initial_layer_print_height` 不算层高：认的是它后面那条正主 */
        assert_eq!(f.layer_height, Some(0.2));
        assert_eq!(f.slicer_version.as_deref(), Some("BambuStudio 02.08.02.60"));
    }

    /// `config_block_end` 之后的行**不看**（那个 9.9 是诱饵）。
    #[test]
    fn stops_at_config_block_end() {
        let f =
            read_head_facts("; layer_height = 0.2\n; config_block_end\n; nozzle_diameter = 9.9\n");
        assert_eq!(f.layer_height, Some(0.2));
        assert_eq!(f.nozzle_diameter, None);
    }

    /// 别的切片器那种头（没有这几行）⇒ 三格全 `None`，不瞎编。
    #[test]
    fn missing_lines_are_none() {
        let f = read_head_facts("; generated by Cura\nG1 X0 Y0\n");
        assert_eq!(f, HeadFacts::default());
    }

    /// 重复出现只认第一次（生效值写在头里，后面的不追）。
    #[test]
    fn first_occurrence_wins() {
        let f = read_head_facts("; nozzle_diameter = 0.4\n; nozzle_diameter = 0.6\n");
        assert_eq!(f.nozzle_diameter, Some(0.4));
    }
}
