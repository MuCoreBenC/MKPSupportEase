function toDataUri(fill: string): string {
  /* 用正则 + /g 而不是 replaceAll：本仓库 tsconfig 的 lib 低于 es2021，
     replaceAll 编不过。为一处调用去抬 lib 不值当。 */
  return `data:image/svg+xml,${encodeURIComponent(MARKUP.replace(/__FILL__/g, fill))}`
}

