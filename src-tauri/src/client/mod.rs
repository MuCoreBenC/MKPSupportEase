//! 正式客户端的数据面 —— 自己的数据根 + 首启释放。
//!
//! # 与工作台的关系：**代码一套，数据根两套**
//!
//! 解析预设的那份代码住在 [`crate::presetdata`]，客户端与工作台共用它。
//! 两边的差别**只在根**：
//!
//! ```text
//! 客户端   Presets::load_from(<appDataDir>/presets)   ← 用户机器上的正式数据
//! 工作台   Presets::load_from(<repo>/presets)         ← 仓库里的开发源数据
//! ```
//!
//! 两边**永不互相读写**，即使跑在同一台开发机上。客户端跑在一台没有仓库的机器上，
//! 所以它这一侧**不许出现任何仓库路径** —— 定义类数据来自编译期打进二进制的内置默认
//! （[`defaults`]），第一次启动释放进自己的数据根（[`paths`]）。

